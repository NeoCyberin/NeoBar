def arc(cx, cy, rx, ry, a0, a1):
    n = max(2, int(math.ceil(abs(a1 - a0) / float(STEP[0]))) + 1)
    pts = []
    for i in range(n):
        a = math.radians(a0 + (a1 - a0) * i / float(n - 1))
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts


def ell(cx, cy, rx, ry):
    pts = arc(cx, cy, rx, ry, 90, 450)
    pts[-1] = pts[0]
    return pts


def bez3(p0, p1, p2, p3, n=14):
    pts = []
    for i in range(n + 1):
        t = i / float(n)
        u = 1 - t
        x = u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0]
        y = u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]
        pts.append((x, y))
    return pts


def P(*parts):
    out = []
    for p in parts:
        if isinstance(p, tuple):
            out.append(p)
        else:
            for q in p:
                if not out or abs(out[-1][0] - q[0]) > 0.01 or abs(out[-1][1] - q[1]) > 0.01:
                    out.append(q)
    return out


def mirror_x(strokes, w):
    return [[(w - x, y) for (x, y) in s] for s in strokes]


def rot180(strokes, cx, cy):
    return [[(2 * cx - x, 2 * cy - y) for (x, y) in s] for s in strokes]


def shift(strokes, dx, dy):
    return [[(x + dx, y + dy) for (x, y) in s] for s in strokes]


def dot(x, y):
    return [(x, y), (x, y + 14)]


