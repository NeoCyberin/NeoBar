# NeoBar: create a SELF-SIGNED code signing certificate for the current Windows user
# and write sign-config.bat so that release.bat / sign.bat use it.
# Run through make-cert.bat. Nothing leaves this computer.
param([string]$Name = "NeoCyberin", [int]$Years = 5)
$ErrorActionPreference = "Stop"

$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$cfg  = Join-Path $root "sign-config.bat"
if (Test-Path $cfg) {
    Write-Host "sign-config.bat already exists: $cfg"
    Write-Host "Delete it first if you really want a new certificate."
    exit 1
}

$cert = New-SelfSignedCertificate -Type CodeSigningCert `
    -Subject "CN=$Name" -KeyAlgorithm RSA -KeyLength 3072 -HashAlgorithm SHA256 `
    -KeyExportPolicy NonExportable -NotAfter (Get-Date).AddYears($Years) `
    -CertStoreLocation "Cert:\CurrentUser\My"

# public part only (can be given to anyone who wants to verify your files)
$cer = Join-Path $root "NeoBar-selfsigned.cer"
Export-Certificate -Cert $cert -FilePath $cer | Out-Null

@"
@echo off
rem Generated by make-cert.bat (self-signed certificate). Not committed: see .gitignore.
set "SIGN_THUMBPRINT=$($cert.Thumbprint)"
set "SIGN_SUBJECT="
set "SIGN_TIMESTAMP=http://time.certum.pl"
set "SIGNTOOL="
"@ | Set-Content -Path $cfg -Encoding ASCII

Write-Host ""
Write-Host "Certificate created: CN=$Name"
Write-Host "Thumbprint: $($cert.Thumbprint)"
Write-Host "Valid until: $($cert.NotAfter)"
Write-Host "sign-config.bat written. Public certificate: $cer"
Write-Host ""
Write-Host "Windows does NOT trust this certificate on any computer, including this one."
Write-Host "Signed files will show it as an untrusted/unknown publisher."
Write-Host "Optionally trust it for the CURRENT USER only on this computer (to test the signature):"
$a = Read-Host "Trust it for the current user here? [y/N]"
if ($a -eq "y" -or $a -eq "Y") {
    Import-Certificate -FilePath $cer -CertStoreLocation "Cert:\CurrentUser\Root" | Out-Null
    Import-Certificate -FilePath $cer -CertStoreLocation "Cert:\CurrentUser\TrustedPublisher" | Out-Null
    Write-Host "Done (current user only). Remove later: certmgr.msc -> Trusted Root / Trusted Publishers."
}
